-- Off-client editor/transaction regressions. No real image or native pass implied.
return function(cameraFixture, eq, test)
    local function make(saved, values)
        local f = cameraFixture(saved, values)
        f.values.ResampleAlwaysSharpen = values and values.ResampleAlwaysSharpen or "0"
        f.values.ResampleSharpness = values and values.ResampleSharpness or "1.0"
        f.values.bloomUserMult = values and values.bloomUserMult or "0.4"
        f.env.C_VideoOptions.IsLinearEnabledOnStart = function() return true end
        f.editor = f.r.photoEditor
        return f
    end
    local function enter(f) assert(f.r.camera.Toggle()); f.flush(); return f.r.composition.editor end
    test("PE01 schema 12 migrates once with settings, names and completion intact; no startup write", function()
        local f = make(); local old = f.ns.Value.Copy(f.r.db)
        old.schemaVersion, old.camera.editor, old.onboarding.completed = 12, nil, true
        old.camera.thirds = true
        local g = make(old); eq(g.r.storeStatus, "MIGRATED_12_TO_21"); eq(g.r.db.schemaVersion, 21)
        eq(g.r.db.onboarding.completed, true); eq(g.r.db.camera.thirds, true); eq(#g.calls, 0)
        eq(old.camera.editor, nil); eq(g.r.db.camera.editor.version, 2)
    end)
    test("PE02 every look control validates, changes only photo data and previews without native writes", function()
        local f = make(); local before = f.ns.Value.Copy(f.r.db.config); local ui = enter(f)
        assert(f.editor.Recipe("ember")); assert(f.editor.Set("glow", .5)); assert(f.editor.Set("grain", .1))
        eq(f.r.photoEffects.root:IsVisible(), true); eq(f.r.photoEffects.root.parent, nil)
        eq(f.r.photoEffects.glow[1].SetBlendModeArgs[1], "ADD")
        eq(f.editor.Set("unknown", 1), nil); eq(f.editor.Set("vignette", -1), nil); eq(f.editor.Set("warmth", 0/0), nil)
        eq(f.r.db.config.studio.modes.nightVision.brightness, before.studio.modes.nightVision.brightness)
        eq(f.r.db.optics.visual.Brightness, nil); eq(#f.calls, 0)
        f.mock.Click("Look"); f.mock.Click("Vignette"); ui.sliders.vignette:SetValue(70); assert(math.abs(f.r.db.camera.editor.look.vignette - .7) < .00001)
        f.mock.Click("Glow"); eq(ui.marker:IsVisible(), true)
    end)
    test("PE03 native drag coalesces movements and applies before release", function()
        local f = make(); local ui = enter(f); ui.tab = "Light"; ui.Build(true)
        local slider = ui.sliders.Brightness
        slider.scripts.OnMouseDown(slider)
        for i = 53, 75 do slider:SetValue(i) end
        eq(#f.calls, 0); f.tick(); eq(#f.calls, 1); eq(f.values.Brightness, "75")
        eq(ui.dragging, slider); slider.scripts.OnMouseUp(slider)
        f.flush(); eq(f.values.Brightness, "75"); eq(f.r.db.camera.editor.session.before.Brightness, "52")
        eq(f.r.db.journal.entries.Brightness.originalRaw, "52")
    end)
    test("PE04 edit entry Enter applies; invalid text does not write", function()
        local f = make(); local ui = enter(f); ui.tab = "Light"; ui.Build()
        local edit = ui.sliders.Contrast.edit
        edit:SetText("999"); edit.scripts.OnEnterPressed(edit); eq(#f.calls, 0)
        edit:SetText("65"); edit.scripts.OnEnterPressed(edit); f.flush(); eq(f.values.Contrast, "65")
    end)
    test("PE05 exact pre-photo brightness and contrast return; original ownership never overwritten", function()
        local f = make(nil, { Brightness = "045.00", Contrast = "060.00" })
        assert(f.r.product.Select("nightVision")); f.flush(); local modeBrightness = f.values.Brightness
        enter(f); assert(f.editor.Native({ Brightness = 82, Contrast = 67 })); f.flush()
        eq(f.r.db.journal.entries.Brightness.originalRaw, "045.00")
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.Brightness, modeBrightness); eq(f.values.Contrast, "060.00")
        eq(f.r.product.active, "nightVision"); eq(f.r.db.camera.editor.session, nil)
        eq(f.r.db.journal.entries.Brightness.originalRaw, "045.00")
    end)
    test("PE06 optics stay canonical and saved mode/quality intent survives", function()
        local f = make(); f.r.db.optics.quality.ResampleSharpness = 1
        enter(f); assert(f.editor.Native({ ResampleSharpness = .4, ResampleAlwaysSharpen = 1, bloomUserMult = .8 })); f.flush()
        eq(f.r.db.optics.quality.ResampleSharpness, 1); eq(next(f.r.db.optics.visual), nil)
        eq(f.r.db.experiments.journal.entries.ResampleSharpness.originalRaw, "1.0")
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.ResampleSharpness, "1.0"); eq(f.values.ResampleAlwaysSharpen, "0")
        eq(f.values.bloomUserMult, "0.4"); eq(f.r.db.camera.editor.session, nil)
    end)
    test("PE07 Before After restores exact scene without altering saved look or mode", function()
        local f = make(); enter(f); f.editor.Recipe("ember")
        assert(f.editor.Native({ Brightness = 70 })); f.flush(); assert(f.editor.Compare()); f.flush()
        eq(f.values.Brightness, "52"); eq(f.editor.before, true); eq(f.r.photoEffects.root:IsShown(), false)
        eq(f.r.db.camera.editor.look.warmth, .55)
        assert(f.editor.Compare()); f.flush(); eq(f.values.Brightness, "70"); eq(f.editor.before, false)
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.Brightness, "52")
    end)
    test("PE08 missing native capabilities isolate the affected control; overlays still work", function()
        local f = make(); f.env.C_VideoOptions.IsLinearEnabledOnStart = nil; f.values.Contrast = nil
        local ui = enter(f); ui.tab = "Light"; ui.Build()
        eq(ui.sliders.Contrast, nil); assert(ui.sliders.Brightness)
        f.mock.Click("Detail"); eq(ui.sliders.bloomUserMult, nil)
        assert(f.editor.Native({ Brightness = 70 })); f.flush(); assert(f.editor.Recipe("night"))
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.Brightness, "52")
    end)
    test("PE09 external edits preserved while independent photo settings restore", function()
        local f = make(); enter(f); assert(f.editor.Native({ Brightness = 70, Contrast = 68 })); f.flush()
        f.values.Brightness = "66"; f.editor.Observe(); local calls = #f.calls
        f.r.camera.Exit(); f.flush(); eq(f.values.Brightness, "66"); eq(f.values.Contrast, "60")
        eq(#f.calls, calls + 1); assert(f.r.db.camera.editor.session.before.Brightness)
        eq(f.r.db.camera.editor.session.before.Contrast, nil); eq(f.r.db.journal.entries.Brightness.originalRaw, "52")
    end)
    test("PE10 setter rejection compensates and does not invent a completed photo", function()
        local f = make(); enter(f)
        f.setter = function(k, v, count) f.values[k] = v; return count ~= 1 end
        f.editor.Native({ Brightness = 70 }); f.flush(); eq(f.values.Brightness, "52")
        eq(f.r.db.camera.editor.session, nil); eq(next(f.r.db.journal.entries), nil)
    end)
    test("PE11 clamping and failed compensation retain recovery and never auto-retry", function()
        local f = make(); enter(f); f.setter = function(k) f.values[k] = "63"; return true end
        f.editor.Native({ Brightness = 70 }); f.flush(); local count = #f.calls
        eq(f.r.db.camera.editor.session.state, "recovery"); eq(f.r.db.journal.entries.Brightness.originalRaw, "52")
        f.r.camera.Exit(); f.flush(); eq(#f.calls, count); eq(f.values.Brightness, "63")
    end)
    test("PE12 reload keeps return intent but never reapplies effects or graphics", function()
        local f = make(); enter(f); f.editor.Recipe("ember"); assert(f.editor.Native({ Contrast = 66 })); f.flush()
        local g = make(f.r.db, f.values); eq(#g.calls, 0); eq(g.editor.active, false); eq(g.r.photoEffects.root, nil)
        assert(g.r.camera.Exit()); g.flush(); eq(g.values.Contrast, "60"); eq(g.r.db.camera.editor.session, nil)
    end)
    test("PE13 clean capture hides editor, drag handle and guides, preserving photo effects", function()
        local f = make(); local ui = enter(f); f.editor.Set("glow", .4); ui.Build()
        f.r.composition.ToggleControls(); eq(ui.panel:IsVisible(), false); eq(ui.marker:IsVisible(), false)
        eq(f.r.photoEffects.root:IsVisible(), true)
        f.r.composition.Capture(); f.tick(); eq(f.captures, 1); eq(f.r.photoEffects.root:IsVisible(), true)
        f.r.composition.root.scripts.OnEvent(f.r.composition.root, "SCREENSHOT_SUCCEEDED"); f.flush()
        eq(ui.panel:IsVisible(), false); f.r.camera.Exit(); eq(f.r.photoEffects.root:IsVisible(), false)
    end)
    test("PE14 Escape during native verification exits after the same bounded operation", function()
        local f = make(); enter(f); assert(f.editor.Native({ Brightness = 70 }))
        local input = f.r.composition.input; input.scripts.OnKeyDown(input, "ESCAPE"); f.flush()
        eq(f.env.UIParent:IsShown(), true); eq(f.r.camera.active, false); eq(f.values.Brightness, "52")
        eq(f.r.db.camera.editor.session, nil)
    end)
    test("PE15 invalid saved look or session is quarantined; data-only transfer round trips", function()
        local f = make(); enter(f); assert(f.editor.Recipe("portrait")); assert(f.editor.Save("Portrait"))
        local code = f.ns.PhotoConfig.Export(f.r.db.camera.editor.look); assert(f.ns.PhotoConfig.Import(code))
        eq(f.ns.PhotoConfig.Import("/run doSomething()"), nil); eq(f.ns.PhotoConfig.Import(code .. ";9"), nil)
        assert(f.editor.Recipe("neutral")); assert(f.editor.Load("Portrait")); eq(f.r.db.camera.editor.look.tint, .15)
        local bad = f.ns.Value.Copy(f.r.db); bad.camera.editor.look.glow = 4; eq(f.ns.Store.Open(bad), nil)
        bad = f.ns.Value.Copy(f.r.db); bad.camera.editor.session = { before = { Gamma = "2" }, after = {}, expected = {}, state = "after" }; eq(f.ns.Store.Open(bad), nil)
        eq(#f.calls, 0)
    end)
    test("PE16 Camera controls fit and scroll at small sizes; all tabs are reachable", function()
        local f = make(); local ui = enter(f)
        for _, tab in ipairs({ "Look", "Light", "Frame", "Saved" }) do
            ui.tab = tab; ui.Build(true); eq(ui.scroll:GetVerticalScroll(), 0); assert(ui.contentHeight > 0)
        end
        ui.tab = "Look"; ui.Build(true); eq(ui.scrollbar.maximum, 0)
        ui.scroll.scripts.OnMouseWheel(ui.scroll, -3); eq(ui.scroll:GetVerticalScroll(), 0)
        f.env.UIParent:SetSize(600, 400); f.r.composition.Show()
        assert(ui.panel:GetHeight() * ui.panel.scale <= 400 - 120)
    end)
    test("PE17 glow position uses drag endpoint and resets without graphics writes", function()
        local f = make(); local ui = enter(f); f.mock.Click("Look"); f.mock.Click("Glow"); f.editor.Set("glow", .5); ui.Build()
        ui.marker.centerX, ui.marker.centerY = 320, 200
        ui.marker.scripts.OnDragStop(ui.marker); eq(f.r.db.camera.editor.look.glowX, .25); eq(f.r.db.camera.editor.look.glowY, .75)
        f.mock.Click("Reset photo look"); eq(f.r.db.camera.editor.look.glow, 0); eq(#f.calls, 0)
    end)
    test("PE18 combat suspends editor/effects without restoring or queuing native edits", function()
        local f = make(); f.r.db.camera.keepInCombat=false; f.r.db.camera.effectsInCombat=false; enter(f); assert(f.editor.Native({ Brightness = 70 })); f.flush(); local calls = #f.calls
        f.env.InCombatLockdown = function() return true end; f.r.camera.Combat()
        eq(f.r.photoEffects.root:IsShown(), false); eq(f.env.UIParent:IsShown(), true); eq(#f.calls, calls)
        eq(f.editor.Native({ Brightness = 80 }), nil); eq(#f.calls, calls)
        f.env.InCombatLockdown = function() return false end; f.flush(); eq(#f.calls, calls)
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.Brightness, "52")
    end)
    test("PE19 model snapshots of the in-scene editor for offline layout inspection", function()
        local f = make(); local ui = enter(f); f.editor.Recipe("ember"); f.editor.Set("glow", .3); f.mock.Click("Look"); ui.Build()
        f.mock.Export("../../outputs/photo-editor-look.tsv")
        for _, tab in ipairs({ "Light", "Frame", "Saved" }) do ui.tab = tab; ui.Build(true); f.mock.Export("../../outputs/photo-editor-" .. tab:lower() .. ".tsv") end
        eq(#f.calls, 0)
    end)
    test("PE20 hiding controls clears editor focus but never another addon's text focus", function()
        local f = make(); local ui = enter(f); f.mock.Click("Look"); ui.sliders.warmth.edit:SetFocus()
        f.r.composition.ToggleControls(); eq(f.mock.focus, nil)
        local input = f.r.composition.input; input.scripts.OnKeyDown(input, "H"); eq(f.r.composition.controlsHidden, false)
        local foreign = f.env.CreateFrame("EditBox", nil, f.env.UIParent); foreign:SetFocus()
        f.r.composition.ToggleControls(); eq(f.mock.focus, foreign); foreign:ClearFocus()
        input.scripts.OnKeyDown(input, "ESCAPE"); eq(f.r.camera.active, false)
    end)
    test("PE21 unavailable effect API leaves Camera and visible exit usable", function()
        local f = make(); local create = f.env.CreateFrame
        f.env.CreateFrame = function(...)
            local frame = create(...); local original = frame.CreateTexture
            frame.CreateTexture = function(self, ...) local t = original(self, ...); t.SetBlendMode = false; return t end
            return frame
        end
        local ui = enter(f); assert(ui.panel:IsVisible()); assert(f.editor.renderError)
        f.mock.Click("Exit Camera Mode"); eq(f.env.UIParent:IsShown(), true); eq(#f.calls, 0)
    end)
    test("PE22 invalid targets, restricted APIs and missing setter never corrupt photo data", function()
        local f = make(); enter(f)
        for _, targets in ipairs({ { Brightness = 101 }, { Contrast = -1 }, { Gamma = 2 }, { bloomUserMult = .3 }, { ResampleSharpness = .45 } }) do
            eq(f.editor.Native(targets), nil); eq(f.r.db.camera.editor.session, nil); eq(#f.calls, 0)
        end
        f.restricted = "Brightness"; eq(f.editor.Native({ Brightness = 70 }), nil); eq(#f.calls, 0)
        f.restricted = nil; f.env.C_CVar.SetCVar = nil; eq(f.editor.Native({ Brightness = 70 }), nil); eq(#f.calls, 0)
        assert(f.editor.Recipe("ember")); assert(f.r.camera.Exit()); eq(f.r.db.camera.editor.session, nil)
    end)
    test("PE23 delayed drift retains recovery and report excludes saved user names", function()
        local f = make(); enter(f); assert(f.editor.Save("Private personal name"))
        assert(f.editor.Native({ Brightness = 70 })); f.values.Brightness = "67"; f.flush()
        eq(f.r.db.camera.editor.session.state, "recovery")
        local report = f.ns.Report.Export(f.r); assert(report:find("photo lighting Brightness return=52", 1, true))
        eq(report:find("Private personal name", 1, true), nil)
        local count = #f.calls; f.r.camera.Exit(); f.flush(); eq(#f.calls, count); eq(f.values.Brightness, "67")
    end)
    test("PE24 exact pre-photo raw mismatch is retained even if numerically equal", function()
        local f = make(nil, { Brightness = "052.00" }); enter(f); assert(f.editor.Native({ Brightness = 70 })); f.flush()
        f.setter = function(k, v) f.values[k] = tostring(tonumber(v)); return true end
        f.r.camera.Exit(); f.flush(); assert(f.r.db.camera.editor.session); assert(f.r.db.journal.entries.Brightness)
        eq(f.env.UIParent:IsShown(), true)
    end)
    test("PE25 releasing a hidden or exited native slider cannot write after exit", function()
        local f = make(); local ui = enter(f); ui.tab = "Frame"; ui.Build()
        local slider = ui.sliders.cameraFov; slider:SetValue(75)
        f.r.composition.ToggleControls(); slider.scripts.OnMouseUp(slider); eq(#f.calls, 0)
        f.r.camera.Exit(); slider.scripts.OnMouseUp(slider); eq(#f.calls, 0); eq(f.values.cameraFov, "090.00")
    end)
    test("PE26 owner fallback to the canonical original releases without replaying pre-photo mode", function()
        local f = make(nil, { Brightness = "45" }); assert(f.r.product.Select("nightVision")); f.flush()
        enter(f); assert(f.editor.Native({ Brightness = 82 })); f.flush(); local calls = #f.calls
        f.values.Brightness = "45"; f.editor.Observe(); f.r.camera.Exit(); f.flush()
        eq(#f.calls, calls); eq(f.values.Brightness, "45"); eq(f.r.db.camera.editor.session, nil)
        eq(f.r.db.journal.entries.Brightness, nil)
        assert(f.r.product.Select("nightVision")); f.flush(); eq(f.values.Brightness, "75")
    end)
end
