-- Deterministic event/timer mocks, not an in-client latency or FPS measurement.
return function(cameraFixture, eq, test)
    local function make()
        local f = cameraFixture()
        f.values.ResampleAlwaysSharpen, f.values.ResampleSharpness, f.values.bloomUserMult = "0", "1", "0.4"
        f.env.C_VideoOptions.IsLinearEnabledOnStart = function() return true end
        assert(f.r.camera.Toggle()); f.flush()
        f.ui, f.p = f.r.composition.editor, f.r.photoPreview
        f.ui.tab = "Light"; f.ui.Build(true)
        return f
    end
    local function drag(f, key, value)
        local slider = assert(f.ui.sliders[key]); slider.scripts.OnMouseDown(slider); slider:SetValue(value); return slider
    end
    test("LIVE01 no startup polling and hundreds of input events collapse into one verified value", function()
        local f = make(); eq(#f.calls, 0); eq(#f.mock.timers, 0)
        local slider = drag(f, "Brightness", 60)
        for i = 1, 300 do slider:SetValue(60 + i % 20) end
        slider:SetValue(79); eq(#f.mock.timers, 1); eq(#f.calls, 0)
        f.tick(); eq(f.values.Brightness, "79"); eq(#f.calls, 1); eq(f.p.busy, true)
        f.tick(); eq(f.p.busy, false); eq(f.ui.dragging, slider); eq(f.ui.sliders.Brightness, slider)
        slider:SetValue(80); f.flush(); eq(#f.calls, 2); eq(f.values.Brightness, "80")
        slider.scripts.OnMouseUp(slider); eq(f.p.Pending(), false); eq(#f.mock.timers, 0)
    end)
    test("LIVE02 input during verification waits and final release keeps only the newest endpoint", function()
        local f = make(); local slider = drag(f, "Brightness", 70); f.tick()
        for i = 71, 90 do slider:SetValue(i) end
        eq(#f.calls, 1); eq(#f.p.order, 1)
        slider.scripts.OnMouseUp(slider); f.tick(); eq(#f.calls, 1)
        f.tick(); eq(#f.calls, 2); eq(f.values.Brightness, "90"); f.flush()
        eq(f.r.db.journal.entries.Brightness.originalRaw, "52")
        eq(f.r.db.camera.editor.session.before.Brightness, "52")
        f.r.camera.Exit(); f.flush(); eq(f.values.Brightness, "52")
    end)
    test("LIVE03 multiple controls retain their latest values and never overlap native transactions", function()
        local f = make(); local b = drag(f, "Brightness", 70); b.scripts.OnMouseUp(b)
        local c = drag(f, "Contrast", 65); c.scripts.OnMouseUp(c)
        f.mock.Click("Detail")
        local s = drag(f, "ResampleSharpness", 80); s.scripts.OnMouseUp(s)
        f.flush(); eq(f.values.Brightness, "70"); eq(f.values.Contrast, "65"); eq(f.values.ResampleSharpness, "0.4")
        eq(f.values.ResampleAlwaysSharpen, "1"); eq(f.p.error, nil)
        assert(f.r.camera.Exit()); f.flush(); eq(f.values.Contrast, "60"); eq(f.values.ResampleSharpness, "1")
    end)
    test("LIVE04 FOV updates while held and Escape during verification restores after finishing", function()
        local f = make(); f.ui.tab = "Frame"; f.ui.Build()
        local slider = drag(f, "cameraFov", 75); f.tick(); eq(f.values.cameraFov, "75")
        slider:SetValue(65)
        local input = f.r.composition.input; input.scripts.OnKeyDown(input, "ESCAPE"); f.flush()
        eq(f.values.cameraFov, "090.00"); eq(f.r.camera.active, false); eq(f.p.Pending(), false)
        for _, call in ipairs(f.calls) do assert(call[2] ~= "65") end
    end)
    test("LIVE05 Capture waits for the released endpoint then hides all controls", function()
        local f = make(); local s = drag(f, "Brightness", 72); f.tick(); s:SetValue(83); s.scripts.OnMouseUp(s)
        assert(f.r.composition.Capture()); eq(f.captures, 0)
        local native = f.env.Screenshot
        f.env.Screenshot = function() eq(f.values.Brightness, "83"); eq(f.r.photoEditor.busy, false); native() end
        f.flush(); eq(f.captures, 1); eq(f.values.Brightness, "83"); eq(f.p.Pending(), false)
    end)
    test("LIVE06 Hide controls waits for the endpoint and does not keep editing a clean shot", function()
        local f = make(); local s = drag(f, "Brightness", 78); s.scripts.OnMouseUp(s)
        assert(f.r.composition.ToggleControls()); eq(f.r.composition.controlsHidden, false)
        f.flush(); eq(f.values.Brightness, "78"); eq(f.r.composition.controlsHidden, true)
        local calls = #f.calls; s:SetValue(89); f.flush(); eq(#f.calls, calls)
        f.r.composition.ToggleControls(); eq(f.r.composition.controlsHidden, false)
    end)
    test("LIVE07 Escape before a queued preview causes zero writes and cancels queued capture", function()
        local f = make(); drag(f, "Brightness", 88); f.r.composition.Capture(); f.r.camera.Exit(); f.flush()
        eq(#f.calls, 0); eq(f.captures, 0); eq(f.p.Pending(), false)
        assert(f.r.camera.Toggle()); f.flush(); eq(#f.calls, 0)
    end)
    test("LIVE08 combat discards pending preview and action without deferred graphics writes", function()
        local f = make(); local s = drag(f, "Brightness", 70); f.tick(); f.tick(); s:SetValue(85)
        f.r.composition.ToggleControls(); f.r.db.camera.keepInCombat=false; f.env.InCombatLockdown = function() return true end; f.r.camera.Combat()
        local count = #f.calls; f.flush(); eq(#f.calls, count); eq(f.env.UIParent:IsShown(), true)
        f.env.InCombatLockdown = function() return false end; f.flush(); eq(#f.calls, count)
        f.r.camera.Exit(); f.flush(); eq(f.values.Brightness, "52")
    end)
    test("LIVE09 a failed transaction halts the drag and clears remaining values without retry", function()
        local f = make(); local s = drag(f, "Brightness", 70)
        f.setter = function(k, v, n) f.values[k] = v; return n ~= 1 end
        f.tick(); s:SetValue(80); f.flush(); eq(f.values.Brightness, "52"); eq(f.p.status, "FAILED")
        local count = #f.calls; s:SetValue(81); f.flush(); eq(#f.calls, count)
        s.scripts.OnMouseUp(s); f.setter = nil; drag(f, "Brightness", 75); f.flush(); eq(f.values.Brightness, "75")
    end)
    test("LIVE10 external change during a drag stops it and preserves exact recovery data", function()
        local f = make(); local s = drag(f, "Brightness", 70); f.tick(); s:SetValue(85)
        f.values.Brightness = "67"; f.flush(); eq(f.values.Brightness, "67"); eq(#f.calls, 1)
        eq(f.p.status, "FAILED"); eq(f.r.db.journal.entries.Brightness.originalRaw, "52")
        f.r.camera.Exit(); f.flush(); eq(f.values.Brightness, "67"); eq(#f.calls, 1)
    end)
    test("LIVE11 Before action drains edits before comparing and Show After returns the endpoint", function()
        local f = make(); local s = drag(f, "Brightness", 82); s.scripts.OnMouseUp(s)
        f.mock.Click("Show Before"); f.flush(); eq(f.r.photoEditor.before, true); eq(f.values.Brightness, "52")
        f.mock.Click("Show After"); f.flush(); eq(f.values.Brightness, "82")
    end)
    test("LIVE12 timer failures and unknown keys do not start writes or create ownership", function()
        local f = make(); eq(f.p.Queue("Gamma", 2), nil); eq(#f.calls, 0)
        f.env.C_Timer.After = function() error("timer unavailable") end
        local s = drag(f, "Brightness", 70); eq(#f.calls, 0); eq(f.p.Pending(), false); eq(f.p.status, "FAILED")
        eq(f.r.db.camera.editor.session, nil); eq(f.r.db.journal.entries.Brightness, nil)
    end)
    test("LIVE13 numeric entry queues one live edit and opening or rebuilding panels never writes", function()
        local f = make(); f.ui.Build(); f.ui.Build(); eq(#f.mock.timers, 0); eq(#f.calls, 0)
        local edit = f.ui.sliders.Contrast.edit; edit:SetText("68"); edit.scripts.OnEnterPressed(edit)
        eq(#f.calls, 0); f.flush(); eq(f.values.Contrast, "68"); eq(#f.calls, 1)
        local report = f.ns.Report.Export(f.r); assert(report:find("Photo live preview: state=IDLE", 1, true))
    end)
    test("LIVE14 page switching retains requested edits without recycling an active drag", function()
        local f = make(); local slider = drag(f, "Brightness", 76); f.tick(); f.tick()
        eq(slider:GetValue(), 76); eq(f.ui.dragging, slider); slider.scripts.OnMouseUp(slider)
        drag(f, "Contrast", 69); f.ui.dragging = nil; f.ui.tab = "Saved"; f.ui.Build(true)
        f.flush(); eq(f.values.Contrast, "69"); eq(f.ui.tab, "Saved")
    end)
    test("LIVE15 a failed preview cancels queued capture and reports failure without hiding exit", function()
        local f = make(); drag(f, "Brightness", 78); f.r.composition.Capture()
        f.setter = function(k) f.values[k] = "63"; return true end
        f.flush(); eq(f.p.status, "FAILED"); eq(f.captures, 0); eq(f.r.composition.root:IsShown(), true)
        assert(f.r.db.journal.entries.Brightness); eq(f.p.action, nil)
        local calls = #f.calls; f.r.camera.Exit(); f.flush(); eq(#f.calls, calls); eq(f.env.UIParent:IsShown(), true)
    end)
    test("LIVE16 FOV remains independent during Before and stale cancelled timers cannot consume new input", function()
        local f = make(); assert(f.r.photoEditor.Compare()); eq(f.r.photoEditor.before, true)
        f.ui.tab = "Frame"; f.ui.Build(); drag(f, "cameraFov", 75); f.flush(); eq(f.values.cameraFov, "75")
        assert(f.r.photoEditor.Compare()); drag(f, "cameraFov", 65)
        f.r.camera.Exit(); f.flush(); eq(f.values.cameraFov, "090.00")
        assert(f.r.camera.Toggle()); f.flush(); f.ui.tab = "Light"; f.ui.Build()
        drag(f, "Brightness", 80); f.p.Cancel("TEST_CANCEL")
        f.p.Begin(); drag(f, "Brightness", 71)
        local calls = #f.calls; f.tick(); eq(#f.calls, calls) -- stale callback cannot steal the new queue
        f.flush(); eq(f.values.Brightness, "71")
    end)
end
